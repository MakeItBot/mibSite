// Helper: get nested key like "hero.title_a"
window.MIB_T = function(lang, key) {
  const parts = key.split(".");
  let v = window.MIB_I18N[lang] || window.MIB_I18N.en;
  for (const p of parts) {
    if (v == null) return key;
    v = v[p];
  }
  return v == null ? key : v;
};

// Apply translations to all [data-i18n] elements + setup language switcher.
window.MIB_APPLY = function(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = window.MIB_T(lang, el.dataset.i18n);
    if (typeof v === "string") el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const v = window.MIB_T(lang, el.dataset.i18nHtml);
    if (typeof v === "string") el.innerHTML = v;
  });
  // List rendering: data-i18n-list="studio.principles"
  document.querySelectorAll("[data-i18n-list]").forEach(el => {
    const v = window.MIB_T(lang, el.dataset.i18nList);
    if (Array.isArray(v)) {
      const tag = el.dataset.i18nListTag || "li";
      el.innerHTML = v.map(item => `<${tag}>${item}</${tag}>`).join("");
    }
  });
  try { localStorage.setItem("mib_lang", lang); } catch (e) {}
  // Notify listeners
  window.dispatchEvent(new CustomEvent("mib-lang-changed", { detail: { lang } }));
};

window.MIB_INIT_LANG = function(defaultLang) {
  let lang = defaultLang || "en";
  try {
    const saved = localStorage.getItem("mib_lang");
    if (saved && window.MIB_I18N[saved]) lang = saved;
  } catch (e) {}
  return lang;
};
